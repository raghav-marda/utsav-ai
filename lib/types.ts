// Core domain types for UtsavAI. Keeping these centralized and strongly
// typed means every module (budget, timeline, vendors, LLM layer) agrees
// on one shape — this is what the rest of the app is validated against.

export type EventType = "wedding" | "birthday" | "community";

export type CityTier = "tier1" | "tier2" | "tier3";

export type BudgetStyle = "lean" | "balanced" | "lavish";

export interface EventBrief {
  eventType: EventType;
  /** Free-text sub-type, e.g. "Sangeet + Reception", "Kids birthday", "Housing society Diwali mela" */
  occasion: string;
  guestCount: number;
  budgetInr: number;
  cityTier: CityTier;
  /** ISO date string for the event day */
  eventDate: string;
  style: BudgetStyle;
  /** Free-text preferences the user types in, used to personalize LLM output */
  preferences: string;
}

export interface BudgetCategory {
  id: string;
  label: string;
  /** Allocation percentage of total budget (0-100) */
  percent: number;
  amountInr: number;
  /** Deterministic rationale generated by the rules engine (not the LLM) */
  rationale: string;
}

export interface BudgetPlan {
  totalInr: number;
  categories: BudgetCategory[];
  /** Running sum check so the UI can flag any rounding drift */
  allocatedInr: number;
  contingencyInr: number;
}

export interface TimelineTask {
  id: string;
  title: string;
  /** Days before the event this task should be completed by */
  daysBefore: number;
  category: string;
  done: boolean;
}

export interface TimelinePlan {
  eventDate: string;
  tasks: TimelineTask[];
}

export interface VendorCategory {
  id: string;
  label: string;
  /** Standard questions every user should ask this vendor type, before any LLM personalization */
  baseQuestions: string[];
  essential: boolean;
}

export interface ChecklistItem {
  id: string;
  vendorCategoryId: string;
  label: string;
  done: boolean;
}

export interface IdeaRequest {
  brief: EventBrief;
  focusArea?: string;
}
